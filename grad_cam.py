# ============================================================
# 6. YOLOv8 WRAPPER
# ============================================================
#
# Grad-CAM normally expects a classification output.
# YOLOv8 is an object detector, so this wrapper extracts the
# class-response channels from the raw detector output.
#
# Output shape expected:
# [batch, 4 + number_of_classes, detections]
#
# First 4 channels = bounding-box information
# Remaining channels = class responses
# ============================================================

class YOLOv8GradCAMWrapper(nn.Module):

    def __init__(self, detector):
        super().__init__()
        self.detector = detector

    def forward(self, x):

        with torch.enable_grad():

            output = self.detector(x)

            # In evaluation mode YOLOv8 normally returns:
            # (predictions, raw_features)
            if isinstance(output, tuple):
                predictions = output[0]

            elif isinstance(output, list):
                predictions = output[0]

            else:
                predictions = output

            if predictions.ndim != 3:
                raise RuntimeError(
                    f"Unexpected YOLO output shape: "
                    f"{predictions.shape}"
                )

            # Remove bounding-box channels
            class_scores = predictions[:, 4:, :]

            # Strongest class response among all detections
            score = class_scores.amax(dim=2).amax(dim=1)

            return score


