def prepare_v5_image(image_path, imgsz=640):

    # Read image
    image_bgr = cv2.imread(image_path)

    if image_bgr is None:
        raise FileNotFoundError(
            f"Could not read image: {image_path}"
        )

    # BGR -> RGB
    original_rgb = cv2.cvtColor(
        image_bgr,
        cv2.COLOR_BGR2RGB
    )

    # YOLOv5 letterbox
    letterboxed = letterbox(
        original_rgb,
        new_shape=imgsz,
        stride=32,
        auto=False
    )[0]

    # Float image for CAM overlay
    input_rgb = (
        letterboxed.astype(np.float32)
        / 255.0
    )

    # HWC -> CHW
    tensor = np.transpose(
        input_rgb,
        (2, 0, 1)
    )

    tensor = np.ascontiguousarray(
        tensor
    )

    # NumPy -> Torch
    input_tensor = torch.from_numpy(
        tensor
    ).float()

    # Add batch dimension
    input_tensor = input_tensor.unsqueeze(0)

    # Device
    input_tensor = input_tensor.to(
        device_v5
    )

    # IMPORTANT FOR GRAD-CAM
    input_tensor = (
        input_tensor
        .clone()
        .detach()
        .requires_grad_(True)
    )

    return (
        original_rgb,
        input_rgb,
        input_tensor
    )


# ============================================================
# 4. YOLOv5 WRAPPER FOR GRAD-CAM
# ============================================================

class YOLOv5Wrapper(torch.nn.Module):

    def __init__(self, model):
        super().__init__()
        self.model = model

    def forward(self, x):

        output = self.model(x)

        # YOLOv5 inference usually returns:
        # (prediction, feature outputs)
        if isinstance(output, (list, tuple)):
            output = output[0]

        return output


wrapped_v5 = YOLOv5Wrapper(
    model_v5
)

wrapped_v5.eval()


# ============================================================
# 5. GRAD-CAM TARGET
#
# YOLOv5 output:
# [x, y, w, h, objectness, class scores...]
#
# Target =
# maximum objectness * class probability response
# for selected class.
# ============================================================

class YOLOv5ClassTarget:

    def __init__(self, class_id):
        self.class_id = class_id

    def __call__(self, model_output):

        if model_output.ndim == 3:
            model_output = model_output[0]

        objectness = model_output[:, 4]

        class_score = model_output[
            :,
            5 + self.class_id
        ]

        score = (
            objectness *
            class_score
        )

        return score.max()


# ============================================================
# 6. FUNCTION TO OBTAIN HIGHEST-CONFIDENCE DETECTION
# ============================================================

def get_main_detection_v5(
    image_path,
    conf_thres=0.25,
    iou_thres=0.60
):

    (
        original_rgb,
        input_rgb,
        input_tensor
    ) = prepare_v5_image(
        image_path
    )

    # Detection does not need gradients
    with torch.no_grad():

        prediction = model_v5(
            input_tensor
        )

        if isinstance(
            prediction,
            (list, tuple)
        ):
            prediction = prediction[0]


        detections = non_max_suppression(
            prediction,
            conf_thres=conf_thres,
            iou_thres=iou_thres
        )


    detection = detections[0]

    if (
        detection is None
        or len(detection) == 0
    ):
        return None


    # YOLOv5 NMS output:
    # x1, y1, x2, y2, confidence, class

    best_index = torch.argmax(
        detection[:, 4]
    )

    best_detection = detection[
        best_index
    ]


    confidence = float(
        best_detection[4].item()
    )

    class_id = int(
        best_detection[5].item()
    )

    bbox = (
        best_detection[:4]
        .detach()
        .cpu()
        .numpy()
    )


    return {
        "class_id": class_id,
        "confidence": confidence,
        "bbox": bbox
    }


